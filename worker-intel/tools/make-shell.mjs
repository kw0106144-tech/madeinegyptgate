#!/usr/bin/env node
/* Reads the built site pages site/tenders/index.html (AR) and site/en/tenders/index.html (EN) — read-only — keeps the
   site-wide <head> assets, header and footer, drops page-specific meta/JSON-LD/scripts and writes src/shell.js.
   The cutting rules live in src/shell-extract.js, shared with the Worker, which loads the same shell from the live site at
   runtime (src/siteshell.js, 1-hour cache). src/shell.js is only the fallback used when the site cannot be read within 1.5 s;
   re-running this after a site build (then `npx wrangler deploy`) keeps that fallback current, but /intel/ pages no longer
   depend on it.
   Usage: node tools/make-shell.mjs [path/to/site] [path/to/out.js] */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { extractShell } from "../src/shell-extract.js";

export { extractShell };
const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(process.argv[2] || join(here, "..", "..", "site"));
const outFile = resolve(process.argv[3] || join(here, "..", "src", "shell.js"));

const ar = extractShell(readFileSync(join(site, "tenders/index.html"), "utf8"), "ar");
const en = extractShell(readFileSync(join(site, "en/tenders/index.html"), "utf8"), "en");
const out = `/* GENERATED by tools/make-shell.mjs from site/tenders/index.html + site/en/tenders/index.html — do not edit by hand.
   Fallback only: the Worker loads the current shell from the site at runtime (src/siteshell.js). Re-run after a site build to
   keep this fallback current, then deploy. */
export const SHELL = ${JSON.stringify({ ar, en, generated_at: new Date().toISOString() }, null, 0)};
`;
writeFileSync(outFile, out);
console.log(outFile + " written:", out.length, "bytes; ar head", ar.head.length, "header", ar.header.length, "footer", ar.footer.length);
